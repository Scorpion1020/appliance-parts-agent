export function localizeText(text: string, locale: Locale): string {
  if (locale === "zh") return chineseText(text);
  return text
    .replace(/^确认之前的加购建议$/, "Confirm the previous cart proposal")
    .replace(/^确认加购建议 (.+)$/, "Confirm cart proposal $1")
    .replace(/^将 ([A-Z0-9-]+) 加入购物车$/, "Add $1 to my cart")
    .replace(/^从购物车移除 ([A-Z0-9-]+)$/, "Remove $1 from my cart")
    .replace(/^查看购物车$/, "Show my cart")
    .replace(/^请求仍在处理中，请稍等后再重试。$/, "This request is still running. Wait before retrying.")
    .replace(/^请求失败，请点击重试以沿用原操作编号。$/, "This request failed. Retry with the same operation ID.");
}

export function localizeStatus(status: string, locale: Locale): string {
  if (locale === "zh") return chineseStatus(status);
  return ZH_TO_EN_STATUS[status] ?? status;
}

