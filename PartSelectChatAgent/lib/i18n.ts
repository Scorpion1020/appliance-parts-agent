export function localizeErrorMessage(code: string | undefined, message: string, locale: Locale): string {
  if (locale === "zh") return chineseText(message);
  if (code && EN_ERRORS[code]) return EN_ERRORS[code];
  if (/[\u4e00-\u9fa5]/.test(message)) return UI_TEXT.en.requestFailed;
  return message;
}
